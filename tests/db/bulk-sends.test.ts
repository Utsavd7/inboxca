import type { Client } from "pg";
import { afterAll,beforeAll,expect,it } from "vitest";
import {actAs,asOwner,attempt,connect,rollback} from "./db";
let db:Client;
beforeAll(async()=>{db=await connect();});
afterAll(async()=>{await db.end();});
it("keeps bulk progress private to its author or leads and queues it once; delivery is server only",()=>rollback(db,async()=>{
  const firm="00000000-0000-4000-8000-000000000ce0",owner="00000000-0000-4000-8000-000000000ce1",staff="00000000-0000-4000-8000-000000000ce2",batch="00000000-0000-4000-8000-000000000ce3";
  await asOwner(db);
  await db.query("insert into auth.users(id,email) values ($1,'owner@bulk.test'),($2,'staff@bulk.test')",[owner,staff]);
  await db.query("insert into public.firms(id,name,state_code,status) values ($1,'Bulk Test Firm','24','active')",[firm]);
  await db.query("insert into public.firm_members(firm_id,user_id,role,status) values ($1,$2,'owner','active'),($1,$3,'staff','active')",[firm,owner,staff]);
  await db.query("insert into public.requests(id,firm_id,kind,entity_type,entity_id,details) values ($1,$2,'bulk_send','bulk_send',$1,jsonb_build_object('by',$3::text))",[batch,firm,owner]);
  expect((await db.query("select count(*)::int n from public.jobs where entity_id=$1 and kind='bulk_send'",[batch])).rows[0].n).toBe(1);
  const client=(await db.query("insert into public.clients(firm_id,name,kind) values ($1,'Invented Client','individual') returning id",[firm])).rows[0].id;
  const doc=(await db.query("insert into public.documents(firm_id,client_id,work_type,document_type,drive_file_id,name,size,sha256) values ($1,$2,'income_tax','ITR-V','invented.pdf','Invented ITR-V',1,'invented') returning id",[firm,client])).rows[0].id;
  const share=(await db.query("insert into public.shares(firm_id,document_id,status,link_token_hash,link_expires_at,delivery) values ($1,$2,'waiting','invented',now()+interval '7 days','{\"state\":\"sending\",\"link_enc\":\"invented encrypted token\"}') returning id",[firm,doc])).rows[0].id;
  await actAs(db,staff);
  expect((await db.query("select id from public.requests where id=$1",[batch])).rows).toEqual([]);
  expect((await attempt(db,"update public.documents set share_policy='auto' where id=$1",[doc])).ok).toBe(false);
  expect((await attempt(db,"select delivery from public.shares where id=$1",[share])).ok).toBe(false);
  expect((await attempt(db,"select public.finish_share($1)",[share])).ok).toBe(false);
  await actAs(db,owner);
  expect((await db.query("select id from public.requests where id=$1",[batch])).rows).toEqual([{id:batch}]);
  expect((await attempt(db,"update public.requests set status='done' where id=$1",[batch])).count).toBe(0);
  await asOwner(db);
  // Sent by a person, the log names them; sent again, nothing more is logged.
  await db.query("select public.finish_share($1,$2)",[share,owner]);
  await db.query("select public.finish_share($1)",[share]);
  expect((await db.query("select status,delivery from public.shares where id=$1",[share])).rows).toEqual([{status:"sent",delivery:{state:"sent"}}]);
  expect((await db.query("select actor_id from public.activity_log where action='document.shared' and entity_id=$1",[doc])).rows).toEqual([{actor_id:owner}]);
}));
